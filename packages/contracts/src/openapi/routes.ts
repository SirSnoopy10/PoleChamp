/** Oznaczenia uprawnień z 03-api §2 – w OpenAPI jako rozszerzenie `x-permissions`. */
export type Permission = 'PUBLIC' | 'ORG' | 'ORG:owner' | 'DEV' | 'JDG' | 'JDG:self' | 'DEV|JDG';

export type HttpMethod = 'get' | 'post' | 'put' | 'patch' | 'delete';

export interface RouteDef {
  method: HttpMethod;
  /** Ścieżka w notacji OpenAPI, np. `/v1/categories/{categoryId}`. */
  path: string;
  operationId: string;
  summary: string;
  permission: Permission;
  body?: z.ZodType;
  query?: z.ZodObject;
  /** Status sukcesu → schemat (null = brak treści). */
  success: { status: number; schema: z.ZodType | null };
  errors: readonly ErrorCode[];
  /** `If-Match` wymagany (03-api §1 – współbieżność). */
  ifMatch?: boolean;
  /** `Idempotency-Key` przyjmowany. */
  idempotent?: boolean;
}

